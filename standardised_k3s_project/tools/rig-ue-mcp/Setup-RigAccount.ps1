<#
.SYNOPSIS
  Rig-side setup for the Unreal (ue-mcp) restricted SSH route (step 2 of README.md's deploy runbook),
  up to but not including the authorized_keys line -- that needs the lab's public key, which the
  lab playbook (ue-mcp-ssh.yml) only prints after this script has installed sshd. Run this
  first, then run Add-RigAuthorizedKey.ps1 once you have that key.
.DESCRIPTION
  Installs OpenSSH Server, creates the restricted non-administrator `uemcp` account, copies
  ue-mcp-policy-wrapper.js from the P:\ projects share (see playbooks/projects-share.yml) to
  C:\watoom\rig-ue-mcp\, installs the reviewed policy (ue-mcp-policy.reviewed.json), adds the sshd Match block and
  dedicated listen port, and opens a Windows Firewall rule scoped to the lab's address only.

  UNTESTED on the rig and against the real ue-mcp server and editor -- see README.md's caveat. Run from an
  Administrator PowerShell. Safe to re-run: every step either checks first or is naturally
  idempotent (Add-WindowsCapability, Set-Content, Add-NetFirewallRule's -ErrorAction below).
.EXAMPLE
  .\Setup-RigAccount.ps1
  .\Setup-RigAccount.ps1 -LabAddress 10.99.20.225 -Port 2224
#>
[CmdletBinding()]
param(
  [string]$LabAddress = '10.99.20.225',
  [int]$Port = 2224,
  [string]$WrapperSource = '',
  [string]$InstallDir = 'C:\watoom\rig-ue-mcp'
)
$ErrorActionPreference = 'Stop'
if (-not $WrapperSource) {
  $local = Join-Path $PSScriptRoot 'ue-mcp-policy-wrapper.js'
  $WrapperSource = if (Test-Path $local) { $local } else {
    'P:\llm\watoom-llm-platform-new-20261112\standardised_k3s_project\tools\rig-ue-mcp\ue-mcp-policy-wrapper.js'
  }
}
Write-Host "Using wrapper source: $WrapperSource"
if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
  throw 'Run this from an Administrator PowerShell.'
}

Write-Host '== OpenSSH Server ==' -ForegroundColor Cyan
if ((Get-WindowsCapability -Online -Name 'OpenSSH.Server~~~~0.0.1.0').State -ne 'Installed') {
  Add-WindowsCapability -Online -Name OpenSSH.Server~~~~0.0.1.0 | Out-Null
}
Start-Service sshd
Set-Service -Name sshd -StartupType Automatic

Write-Host '== Restricted account: uemcp ==' -ForegroundColor Cyan
if (-not (Get-LocalUser -Name uemcp -ErrorAction SilentlyContinue)) {
  $pw = ConvertTo-SecureString (New-Guid).Guid -AsPlainText -Force
  New-LocalUser -Name uemcp -Password $pw -PasswordNeverExpires -AccountNeverExpires `
      -Description "Restricted: ue-mcp policy wrapper only"
} else {
  Write-Host 'uemcp already exists, leaving it as is'
}

Write-Host '== Policy wrapper ==' -ForegroundColor Cyan
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
$wrapperDest = Join-Path $InstallDir 'ue-mcp-policy-wrapper.js'
# Running this script from the install folder makes source and destination the same file, which Copy-Item refuses.
if ((Resolve-Path $WrapperSource).Path -ne (Join-Path (Resolve-Path $InstallDir).Path 'ue-mcp-policy-wrapper.js')) {
  Copy-Item $WrapperSource $wrapperDest -Force
}
Get-Content (Join-Path $InstallDir 'ue-mcp-policy-wrapper.js') -TotalCount 1

Write-Host '== Policy file ==' -ForegroundColor Cyan
New-Item -ItemType Directory -Force -Path C:\ProgramData\watoom | Out-Null
# The reviewed policy is ue-mcp-policy.reviewed.json beside this script (generated by tools/language-knowledge/extract/
# ue_mcp_entries.py): every one of the 31 categories is allowed and nothing is denied (opened by the owner 2026-11-14).
# Decisions are on category.method; deny wins. Re-copy this file to change the live policy.
$policySource = Join-Path $PSScriptRoot 'ue-mcp-policy.reviewed.json'
if (Test-Path $policySource) {
  Copy-Item $policySource C:\ProgramData\watoom\ue-mcp-policy.json -Force
} else {
  Write-Warning 'ue-mcp-policy.reviewed.json not found beside this script: installing the discovery-only baseline (the route will do almost nothing until the reviewed file is copied).'
  '{"allow": ["project.get_status","project.get_info","project.describe_action","project.search_tools","project.list_content_assets"], "deny": []}' `
      | Set-Content C:\ProgramData\watoom\ue-mcp-policy.json
}

Write-Host '== sshd_config: Match block + dedicated port ==' -ForegroundColor Cyan
$sshdConfig = 'C:\ProgramData\ssh\sshd_config'
$current = Get-Content $sshdConfig -Raw
if ($current -notmatch 'Match User uemcp') {
  Add-Content $sshdConfig @"

Match User uemcp
    AuthenticationMethods publickey
    PasswordAuthentication no
    AllowTcpForwarding no
    X11Forwarding no
    PermitTTY no
    AuthorizedKeysFile C:/ProgramData/ssh/uemcp_authorized_keys
Match all
"@
} else {
  Write-Host 'Match User uemcp block already present, leaving it as is'
}
if ($current -notmatch "(?m)^Port $Port$") {
  Add-Content $sshdConfig "Port $Port"
} else {
  Write-Host "Port $Port already configured"
}
Restart-Service sshd

Write-Host '== Firewall: inbound from the lab only ==' -ForegroundColor Cyan
if (-not (Get-NetFirewallRule -Name sshd-ue-mcp -ErrorAction SilentlyContinue)) {
  New-NetFirewallRule -Name sshd-ue-mcp -DisplayName 'OpenSSH ue-mcp (restricted)' `
      -Enabled True -Direction Inbound -Protocol TCP -Action Allow -LocalPort $Port -RemoteAddress $LabAddress
} else {
  Write-Host 'sshd-ue-mcp firewall rule already exists, leaving it as is'
}

Write-Host "Done. Next: run the lab playbook (ue-mcp-ssh.yml), then Add-RigAuthorizedKey.ps1 -PublicKey '<printed key>'." -ForegroundColor Green
